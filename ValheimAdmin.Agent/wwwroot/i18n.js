let current = 'en';
try {
  const saved = localStorage.getItem('va_lang');
  if (saved === 'en' || saved === 'ru') current = saved;
  else if ((navigator.language || '').toLowerCase().startsWith('ru')) current = 'ru';
} catch { /* storage may be unavailable */ }

const listeners = new Set();

export const lang = () => current;
export const languages = Object.keys(dict);

export function setLang(l) {
  if (!dict[l] || l === current) return;
  current = l;
  document.documentElement.lang = l;
  listeners.forEach(fn => fn(l));
}

export function onLangChange(fn) { listeners.add(fn); }

export function t(key, ...args) {
  const s = dict[current][key] ?? dict.en[key] ?? key;
  return args.length ? s.replace(/\{(\d+)\}/g, (_, i) => args[i] ?? '') : s;
}

/** Fills elements marked with data-t="key". */
export function applyStatic() {
  document.documentElement.lang = current;
  document.querySelectorAll('[data-t]').forEach(el => { el.textContent = t(el.dataset.t); });
}

